//! Keeping signatures current.
//!
//! Redoubt pulls from two kinds of source, for a reason worth stating:
//!
//! 1. **ClamAV main/daily, via `freshclam`.** ClamAV's CDN answers only to
//!    their own client, and rather than impersonate it we drive the real
//!    thing. That is also strictly better engineering: freshclam does
//!    incremental `.cdiff` updates (kilobytes, not the 200 MB full container),
//!    mirror failover, and DNS-based version checks. Reimplementing all of
//!    that badly would be the alternative.
//!
//! 2. **Third-party ClamAV-format sources**, fetched directly. Sanesecurity
//!    and abuse.ch publish plain `.ndb`/`.hdb`/`.hsb` files and explicitly
//!    permit direct download, so those we fetch ourselves - with conditional
//!    requests, so a poll that finds nothing new costs one 304.
//!
//! Everything lands in one directory, and [`crate::compile::compile_dir`]
//! turns the lot into a single index.

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::compile::{compile_dir_with, CompileReport};
use crate::config::Config;

/// A third-party signature file fetched directly over HTTPS.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DirectSource {
    /// Filename to store it as. Its extension decides how it is parsed.
    pub name: String,
    pub url: String,
}

/// Identify ourselves honestly. Nothing here pretends to be another client.
fn user_agent() -> String {
    format!("Redoubt/{} (+https://github.com/ernestdefoe/redoubt)", crate::VERSION)
}

fn agent() -> ureq::Agent {
    ureq::Agent::config_builder()
        .user_agent(user_agent())
        .timeout_global(Some(std::time::Duration::from_secs(300)))
        .build()
        .into()
}

