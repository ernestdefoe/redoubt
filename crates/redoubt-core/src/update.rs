/// Where ClamAV usually installs on Windows.
const FRESHCLAM_CANDIDATES: &[&str] = &[
    r"C:\Program Files\ClamAV\freshclam.exe",
    r"C:\Program Files (x86)\ClamAV\freshclam.exe",
    r"C:\ClamAV\freshclam.exe",
];

/// Locate `freshclam`, preferring an explicit configured path.
pub fn find_freshclam(configured: Option<&Path>) -> Option<PathBuf> {
    if let Some(p) = configured {
        return p.is_file().then(|| p.to_path_buf());
    }
    FRESHCLAM_CANDIDATES
        .iter()
        .map(PathBuf::from)
        .find(|p| p.is_file())
}

/// Write a Redoubt-owned `freshclam.conf` pointing at our signature directory.
///
/// We never touch ClamAV's own config: this file lives in Redoubt's data
/// directory and is passed explicitly with `--config-file`, so a user who also
/// runs ClamAV normally is unaffected.
pub fn write_freshclam_config(
    config_path: &Path,
    database_dir: &Path,
    log_path: &Path,
    mirror: &str,
) -> Result<()> {
    if let Some(parent) = config_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::create_dir_all(database_dir)?;

    let body = format!(
        "# Generated by Redoubt {}. Edits will be overwritten.\n\
         DatabaseDirectory {}\n\
         UpdateLogFile {}\n\
         DatabaseMirror {}\n\
         LogTime yes\n\
         LogVerbose no\n\
         ConnectTimeout 30\n\
         ReceiveTimeout 300\n\
         MaxAttempts 3\n\
         ScriptedUpdates yes\n",
        crate::VERSION,
        database_dir.display(),
        log_path.display(),
        mirror,
    );
    std::fs::write(config_path, body)
        .with_context(|| format!("writing {}", config_path.display()))?;
    Ok(())
}

/// Outcome of a freshclam run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FreshclamOutcome {
    /// Databases were updated.
    Updated,
    /// Everything was already current.
    UpToDate,
    /// freshclam is not installed.
    NotInstalled,
    /// It ran and failed.
    Failed { code: Option<i32>, detail: String },
}

/// freshclam draws a progress bar by rewriting one line with carriage
/// returns. Captured through a pipe there are no terminal semantics, so every
/// redraw arrives as its own line - tens of thousands of them. They carry no
/// information once the download is done, so they are dropped.
fn is_progress_noise(line: &str) -> bool {
    line.starts_with("Time:") || line.contains("ETA:")
}

/// Run freshclam against Redoubt's own database directory.
///
/// `on_line` receives freshclam's output as it is parsed, so a CLI can echo
/// progress. freshclam writes to stdout when given `--stdout`.
pub fn run_freshclam(
    exe: &Path,
    config_path: &Path,
    mut on_line: impl FnMut(&str),
) -> Result<FreshclamOutcome> {
    let output = Command::new(exe)
        .arg(format!("--config-file={}", config_path.display()))
        .arg("--stdout")
        .output()
        .with_context(|| format!("running {}", exe.display()))?;

    let text = String::from_utf8_lossy(&output.stdout).into_owned()
        + &String::from_utf8_lossy(&output.stderr);
    for line in text.lines() {
        let line = line.trim();
        if !line.is_empty() && !is_progress_noise(line) {
            on_line(line);
        }
    }

    if output.status.success() {
        // freshclam exits 0 both when it updated and when nothing was stale;
        // the wording is the only way to tell the two apart.
        let updated = text.contains("updated") || text.contains("Downloading");
        return Ok(if updated { FreshclamOutcome::Updated } else { FreshclamOutcome::UpToDate });
    }

    // Trim to the lines that actually explain the failure.
    let detail = text
        .lines()
        .filter(|l| {
            let l = l.trim();
            l.starts_with("ERROR") || l.starts_with("WARNING") || l.contains("error")
        })
        .take(5)
        .collect::<Vec<_>>()
        .join("; ");

    Ok(FreshclamOutcome::Failed {
        code: output.status.code(),
        detail: if detail.is_empty() {
            text.lines().rev().take(3).collect::<Vec<_>>().join("; ")
        } else {
            detail
        },
    })
}

